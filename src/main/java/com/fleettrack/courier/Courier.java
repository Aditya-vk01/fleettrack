package com.fleettrack.courier;

import java.time.Instant;

import com.fleettrack.common.exception.ConflictException;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import jakarta.persistence.Version;

/**
 * A courier and their latest known position.
 *
 * <p>The table also has a {@code last_location geography(Point,4326)} column. It is
 * GENERATED by PostgreSQL from last_latitude/last_longitude, so it is deliberately not
 * mapped here: the entity stays plain JPA (no hibernate-spatial), and spatial queries
 * use it through native SQL in {@link CourierRepository}.
 */
@Entity
@Table(name = "couriers")
public class Courier {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, length = 100)
    private String name;

    @Column(nullable = false, length = 20)
    private String phone;

    @Enumerated(EnumType.STRING)
    @Column(name = "vehicle_type", nullable = false, length = 20)
    private VehicleType vehicleType;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private CourierStatus status;

    @Column(name = "last_latitude")
    private Double lastLatitude;

    @Column(name = "last_longitude")
    private Double lastLongitude;

    @Column(name = "last_seen_at")
    private Instant lastSeenAt;

    /** Optimistic locking: two concurrent writes to the same courier can't silently overwrite each other. */
    @Version
    @Column(nullable = false)
    private Long version;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected Courier() {
        // for JPA
    }

    public Courier(String name, String phone, VehicleType vehicleType) {
        this.name = name;
        this.phone = phone;
        this.vehicleType = vehicleType;
        this.status = CourierStatus.OFFLINE;
    }

    @PrePersist
    void onCreate() {
        Instant now = Instant.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    @PreUpdate
    void onUpdate() {
        this.updatedAt = Instant.now();
    }

    /** Courier toggles themselves online/offline. BUSY is controlled by the delivery lifecycle only. */
    public void changeAvailability(CourierStatus target) {
        if (target == CourierStatus.BUSY) {
            throw new ConflictException("A courier becomes BUSY only by being assigned a delivery");
        }
        if (status == CourierStatus.BUSY) {
            throw new ConflictException("Courier " + id + " has an active delivery and cannot change availability");
        }
        this.status = target;
    }

    public void markBusy() {
        if (status != CourierStatus.AVAILABLE) {
            throw new ConflictException("Courier " + id + " is " + status + ", not AVAILABLE");
        }
        this.status = CourierStatus.BUSY;
    }

    public void releaseFromDelivery() {
        if (status == CourierStatus.BUSY) {
            this.status = CourierStatus.AVAILABLE;
        }
    }

    public Long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getPhone() {
        return phone;
    }

    public VehicleType getVehicleType() {
        return vehicleType;
    }

    public CourierStatus getStatus() {
        return status;
    }

    public Double getLastLatitude() {
        return lastLatitude;
    }

    public Double getLastLongitude() {
        return lastLongitude;
    }

    public Instant getLastSeenAt() {
        return lastSeenAt;
    }

    public Long getVersion() {
        return version;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
