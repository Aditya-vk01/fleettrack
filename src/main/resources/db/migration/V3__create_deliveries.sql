CREATE TABLE deliveries (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_name    VARCHAR(100)     NOT NULL,
    recipient_phone   VARCHAR(20)      NOT NULL,

    pickup_address    VARCHAR(255),
    pickup_latitude   DOUBLE PRECISION NOT NULL,
    pickup_longitude  DOUBLE PRECISION NOT NULL,
    pickup_location   GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(pickup_longitude, pickup_latitude), 4326)::geography) STORED,

    dropoff_address   VARCHAR(255),
    dropoff_latitude  DOUBLE PRECISION NOT NULL,
    dropoff_longitude DOUBLE PRECISION NOT NULL,
    dropoff_location  GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(dropoff_longitude, dropoff_latitude), 4326)::geography) STORED,

    status            VARCHAR(20)      NOT NULL DEFAULT 'CREATED',
    courier_id        BIGINT REFERENCES couriers (id),

    version           BIGINT           NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ      NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ      NOT NULL DEFAULT now(),
    assigned_at       TIMESTAMPTZ,
    picked_up_at      TIMESTAMPTZ,
    delivered_at      TIMESTAMPTZ,
    cancelled_at      TIMESTAMPTZ,

    CONSTRAINT ck_deliveries_status CHECK (status IN
        ('CREATED', 'ASSIGNED', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED')),
    -- Anything past CREATED (except a cancel straight from CREATED) must have a courier.
    CONSTRAINT ck_deliveries_courier_required CHECK (status IN ('CREATED', 'CANCELLED') OR courier_id IS NOT NULL),
    CONSTRAINT ck_deliveries_pickup_latitude CHECK (pickup_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_deliveries_pickup_longitude CHECK (pickup_longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_deliveries_dropoff_latitude CHECK (dropoff_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_deliveries_dropoff_longitude CHECK (dropoff_longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_deliveries_status ON deliveries (status);
CREATE INDEX idx_deliveries_courier_id ON deliveries (courier_id);
CREATE INDEX idx_deliveries_pickup_location ON deliveries USING GIST (pickup_location);

-- Last line of defence against double-booking: even if two requests race past the
-- application checks, the database refuses a second active delivery for one courier.
CREATE UNIQUE INDEX uq_deliveries_one_active_per_courier
    ON deliveries (courier_id)
    WHERE status IN ('ASSIGNED', 'PICKED_UP', 'IN_TRANSIT');

-- Audit trail of every state change (normalized: one row per transition).
CREATE TABLE delivery_status_changes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id BIGINT      NOT NULL REFERENCES deliveries (id) ON DELETE CASCADE,
    from_status VARCHAR(20),
    to_status   VARCHAR(20) NOT NULL,
    courier_id  BIGINT REFERENCES couriers (id),
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_delivery_status_changes_delivery ON delivery_status_changes (delivery_id, changed_at);
