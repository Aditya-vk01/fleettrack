-- Append-only history of every location ping a courier sends.
CREATE TABLE courier_locations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    courier_id      BIGINT           NOT NULL REFERENCES couriers (id) ON DELETE CASCADE,
    latitude        DOUBLE PRECISION NOT NULL,
    longitude       DOUBLE PRECISION NOT NULL,
    location        GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (
        ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)::geography) STORED,
    speed_kmh       DOUBLE PRECISION,
    heading_degrees DOUBLE PRECISION,
    recorded_at     TIMESTAMPTZ      NOT NULL,
    received_at     TIMESTAMPTZ      NOT NULL DEFAULT now(),

    CONSTRAINT ck_courier_locations_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_courier_locations_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_courier_locations_speed CHECK (speed_kmh IS NULL OR speed_kmh >= 0),
    CONSTRAINT ck_courier_locations_heading CHECK (heading_degrees IS NULL OR (heading_degrees >= 0 AND heading_degrees < 360))
);

-- "Show me courier X's recent trail" -> index range scan, newest first.
CREATE INDEX idx_courier_locations_courier_recorded ON courier_locations (courier_id, recorded_at DESC);
-- Spatial analytics over history (e.g. "which couriers passed through this area?").
CREATE INDEX idx_courier_locations_location ON courier_locations USING GIST (location);
