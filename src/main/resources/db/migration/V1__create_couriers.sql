-- PostGIS gives us real geography types and GiST spatial indexes.
CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE couriers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100)     NOT NULL,
    phone          VARCHAR(20)      NOT NULL,
    vehicle_type   VARCHAR(20)      NOT NULL,
    status         VARCHAR(20)      NOT NULL DEFAULT 'OFFLINE',

    -- Latest known position. The application writes plain lat/lng;
    -- the database derives the geography column, so the two can never disagree.
    last_latitude  DOUBLE PRECISION,
    last_longitude DOUBLE PRECISION,
    last_location  GEOGRAPHY(Point, 4326) GENERATED ALWAYS AS (
        CASE WHEN last_latitude IS NULL OR last_longitude IS NULL THEN NULL
             ELSE ST_SetSRID(ST_MakePoint(last_longitude, last_latitude), 4326)::geography
        END) STORED,
    last_seen_at   TIMESTAMPTZ,

    version        BIGINT           NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ      NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ      NOT NULL DEFAULT now(),

    CONSTRAINT uq_couriers_phone UNIQUE (phone),
    CONSTRAINT ck_couriers_status CHECK (status IN ('AVAILABLE', 'BUSY', 'OFFLINE')),
    CONSTRAINT ck_couriers_vehicle_type CHECK (vehicle_type IN ('BICYCLE', 'MOTORBIKE', 'CAR', 'VAN')),
    CONSTRAINT ck_couriers_latitude CHECK (last_latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_couriers_longitude CHECK (last_longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_couriers_position_pair CHECK ((last_latitude IS NULL) = (last_longitude IS NULL))
);

-- "Nearest available courier within radius" hits this index, not the location history,
-- so it stays fast no matter how much history accumulates.
CREATE INDEX idx_couriers_last_location ON couriers USING GIST (last_location);
CREATE INDEX idx_couriers_status ON couriers (status);
